  $md$## Recognition is not recall

A formula can look completely familiar on a page but remain unavailable during an exam. This happens because rereading trains recognition: the information feels known when it is visible. An exam requires recall: producing the information when only the problem is visible.

Active recall closes this gap by making your brain generate the formula before seeing it. The effort involved is useful. Difficulty during retrieval is not evidence that the method is failing; it is the part that strengthens memory.

> If the formula is always visible while you study, you are practising recognition—not exam-day recall.

## Start with blank-page retrieval

Choose one chapter and close your notes. Write every relevant formula you can remember. Include variable meanings, units, and important conditions. Then compare your page with a reliable source and correct omissions in a different colour.

Do not immediately copy the missing formulas several times. Close the source and retrieve them again after a short delay. Retrieval, checking, and another retrieval creates a stronger learning cycle than copying.

## Learn when a formula applies

Memorising symbols without conditions leads to application mistakes. For every formula, ask:

- What does each variable represent?
- Which units should be used?
- What assumptions does the relationship make?
- What clues in a question suggest this formula?
- How would the formula change if a condition changed?

For physics, connect the formula with a diagram or physical situation. For mathematics, connect it with the type of expression or geometric relationship. Understanding gives memory more routes for retrieval.

## Combine recall with questions

After recalling a group of formulas, solve one direct question and one mixed application. The direct question checks basic use. The mixed question checks whether you can select the correct relationship when several seem possible.

If you choose the wrong formula, record why. Did a keyword mislead you? Did you ignore a condition? Did two formulas look similar? Add that distinction to your next recall prompt.

## Space the reviews

Repeat retrieval after approximately one day, three days, one week, and two weeks. The schedule does not need to be perfect. The important principle is to allow some forgetting before retrieving again.

Keep sessions short. Ten minutes of blank-page recall across several days is often more effective than rewriting a formula sheet for an hour in one evening.

## Mix chapters as the exam approaches

Early practice can stay chapter-specific. Later, use mixed prompts that require you to identify the topic before recalling the formula. Real exams do not label each question with the exact rule needed.

Try a “formula trigger” exercise: write a situation such as “projectile at maximum height” or “sum of an arithmetic sequence,” then list the relevant relationships and conditions. Reverse the task by looking at a formula and describing a question where it would be useful.

Your final formula sheet should become shorter over time. Remove relationships you retrieve reliably and focus attention on easily confused, frequently tested, or condition-sensitive formulas.$md$,
