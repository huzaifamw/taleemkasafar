A mock test is a diagnostic tool. The score tells you where you are, but the review tells you how to move. Students who repeatedly attempt papers without analysing them often repeat the same mistakes under slightly different wording.

Take a short break after finishing, then review while your reasoning is still fresh. Keep the question paper, your selected answers, and a notebook or error log together. Your goal is to explain every lost mark—not merely read the correct option.

> The most valuable question after a mock is not “What did I score?” It is “Why did I lose each mark?”

## Start with the paper as a whole

Before opening individual questions, record the overall result: score, accuracy, questions attempted, questions skipped, and time used. Then look at subject-level performance. A reasonable total can hide a serious weakness in one section, while a disappointing total may include a strong subject worth maintaining.

Also note how the test felt. Did you rush the final section? Did one difficult question affect your confidence? Did you take too long to settle into the paper? These observations help explain patterns that raw scores cannot.

## Classify every lost mark

Use four categories for incorrect and skipped questions:

- **Knowledge gap:** You did not know the concept, fact, or formula.
- **Application gap:** You knew the idea but could not apply it in this form.
- **Reading error:** You missed a condition, unit, sign, or keyword.
- **Time decision:** You spent too long, rushed, or left the question too late.

Be honest about the cause. Calling every mistake “careless” hides the behaviour that needs to change. If you forgot that velocity is a vector, it is a knowledge gap. If you knew it but ignored the negative direction in the question, it is a reading or application error.

