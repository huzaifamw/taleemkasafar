## Use the block deliberately

Work on one type of task for the full block. When a question is confusing, mark it and continue rather than opening several videos or searching across multiple websites. Switching resources too quickly creates the feeling of activity while weakening concentration.

Reserve the final three minutes for a short review. Write what you understood, what remains unclear, and the first action for your next block. This note prevents the next session from starting at zero and gives you a record of actual progress.

After the timer ends, take a genuine five-minute break. Stand up, look away from the screen, stretch, or walk briefly. Social media is usually a poor break because it introduces new information and makes returning harder. After four focus blocks, take a longer break of 20 to 30 minutes.

