  $md$## Time is a scoring resource

In a timed MCQ exam, every minute has an opportunity cost. A difficult question can consume the time needed for several straightforward ones. Strong time management is not about answering every question quickly; it is about investing attention where it has the highest chance of producing marks.

Your strategy should be decided and practised before exam day. A plan invented under pressure is easily abandoned when the first difficult question appears.

> Skipping is not surrender. It is a decision to protect the rest of your paper.

## Calculate a useful pace

Divide the available answering time by the number of questions, after reserving a final review buffer. This gives an average pace, not a strict limit for every item. Some questions will take seconds; others deserve more time.

For example, if you have 100 minutes for 80 questions and reserve 10 minutes for review, your working average is slightly over one minute per question. Use this figure to create section checkpoints rather than watching the clock after every item.

## Use a three-pass system

Move through the paper with a different intention on each pass:

- **Pass one:** Answer questions you can solve confidently and quickly. Mark uncertain items and continue.
- **Pass two:** Return to questions that need calculation, comparison, or closer reasoning.
- **Pass three:** Handle the hardest remaining items, educated guesses, and final checks.

The first pass builds marks and confidence. It also gives you a realistic picture of remaining time. Do not turn it into a race: read each question carefully enough to avoid losing easy marks.

## Create section checkpoints

If the exam contains separate subjects, assign each a target completion time. Write those checkpoints during practice and compare them with actual performance. If one section consistently exceeds its allowance, investigate why. The cause may be weak knowledge, slow calculations, excessive rechecking, or reluctance to skip.

Use broad checkpoints such as “complete physics by 10:40” instead of checking the clock after every question. Constant time monitoring consumes attention and increases anxiety.

## Decide when to move on

Create a simple rule for stalled questions. If you have no clear approach after the first reading and a brief attempt, mark it and continue. If you have made meaningful progress on a calculation, a little more time may be justified.

Watch for sunk-cost thinking: spending two minutes on a question does not mean you must spend two more. The earlier time is already gone. Decide based on the probability of earning the mark from this point forward.

## Protect the final review

Use the final minutes to check unanswered questions, response-sheet alignment, units, negative signs, and questions you deliberately marked. Avoid changing an answer only because it “feels too easy.” Change it when you identify a specific error or stronger reasoning.

