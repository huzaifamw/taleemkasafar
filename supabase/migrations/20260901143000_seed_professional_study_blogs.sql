For a knowledge gap, review the smallest relevant concept rather than rereading the entire chapter. Close the notes and explain the concept in your own words. Then solve three to five similar questions without looking at the solution.

For an application gap, compare your reasoning with a correct worked method. Identify the exact step where the paths separated. Redo the question from a blank page, followed by a different question using the same principle.

